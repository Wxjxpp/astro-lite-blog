// Regenerates src/styles/fonts.css: only the numbered unicode-range slices of Noto Serif SC (woff2),
// i.e. none of the latin / cyrillic / vietnamese sets and not the multi-MB unsliced file.
// Usage: node scripts/gen-cjk-fonts.mjs
import { readFileSync, writeFileSync } from 'node:fs';

const dir = 'node_modules/@fontsource/noto-serif-sc';
let out = `/* GENERATED by scripts/gen-cjk-fonts.mjs — Noto Serif SC (思源宋体) CJK slices, weights 400 and 700.
   Loaded as a separate, non-blocking file (/fonts.css). Latin faces are declared inline in BaseLayout. */\n`;
for (const weight of [400, 700]) {
  const css = readFileSync(`${dir}/${weight}.css`, 'utf8');
  const faces = css.split(/\/\* noto-serif-sc-/).slice(1);
  let n = 0;
  for (const block of faces) {
    const m = block.match(/^\[(\d+)\]-\d+-normal \*\/\s*(@font-face \{[\s\S]*?\n\})/); // numbered slices only
    if (!m) continue;
    const range = m[2].match(/unicode-range:\s*([^;]+);/)[1];
    out += `@font-face{font-family:'Noto Serif SC';font-style:normal;font-display:swap;font-weight:${weight};` +
      `src:url(../../${dir}/files/noto-serif-sc-${m[1]}-${weight}-normal.woff2) format('woff2');unicode-range:${range}}\n`;
    n++;
  }
  console.log(`weight ${weight}: ${n} slices`);
}
writeFileSync('src/styles/fonts.css', out);
